# 2. إعداد ذاكرة المحادثة في Streamlit لحفظ الشات
if "messages" not in st.session_state:
    st.session_state.messages = []

# عرض الرسائل السابقة
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# 3. استقبال سؤال المستخدم
if user_input := st.chat_input("اسألني عن أي تفاصيل عقارية..."):
    with st.chat_message("user"):
        st.markdown(user_input)

    st.session_state.messages.append({"role": "user", "content": user_input})

    try:
        with st.chat_message("assistant"):
            with st.spinner("جاري التفكير..."):
                response = client.chat.completions.create(
                    model="openai/gpt-oss-20b",  # موديل حديث وسريع من Groq
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT},
                        *st.session_state.messages
                    ],
                )
                output_text = response.choices[0].message.content
                st.markdown(output_text)

        st.session_state.messages.append({"role": "assistant", "content": output_text})

    except Exception as e:
        st.error(f"حدث خطأ أثناء الاتصال بـ Groq: {e}")